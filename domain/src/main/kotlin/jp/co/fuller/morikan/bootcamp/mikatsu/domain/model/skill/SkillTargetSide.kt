package jp.co.fuller.morikan.bootcamp.mikatsu.domain.model.skill

/**
 * スキルが対象にする陣営(敵か味方か)。
 *
 * スキル一覧にはまだこの列がないが、通常攻撃(敵を殴る)とディア(味方を回復する)で対象にする側が
 * 異なり、戦闘ロジックが対象の妥当性を判定するのに必要なため、シートが陣営を表現するようになる
 * までの間、別のフィールドとして持つ。陣営は使用者から見た相対で、[ENEMY]は使用者の反対の陣営、
 * [ALLY]は使用者と同じ陣営を指す(使用者が敵のときは、味方陣営が[ENEMY]になる)。
 * 範囲が[SkillArea.FIELD]のスキルは、この値に関わらず両陣営を選べる。
 */
enum class SkillTargetSide {
    /** 敵陣営の個体を対象にする。 */
    ENEMY,

    /** 自分を含む味方陣営の個体を対象にする。 */
    ALLY,
}
